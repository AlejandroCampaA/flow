export function CatIcon({ cat, size = 15, className = '' }: { cat: CatMov; size?: number; className?: string }): JSX.Element {
  const u = catUsuario(cat)
  const I = (u ? ICONOS_LIBRES[u.icono] : ICONOS[cat as CatBase]) ?? Tag
  return <I size={size} className={className} aria-hidden />
}
